import fs from 'node:fs/promises';
import * as T from 'three';
import {FBXLoader} from 'three/addons/loaders/FBXLoader.js';
import {GLTFExporter} from 'three/addons/exporters/GLTFExporter.js';
import {createCanvas,loadImage,Image,Canvas} from '@napi-rs/canvas';
globalThis.window=globalThis;globalThis.HTMLImageElement=Image;globalThis.HTMLCanvasElement=Canvas;
globalThis.document={createElement:()=>{const c=createCanvas(1,1);c.toBlob=(cb,type)=>cb(new Blob([c.toBuffer(type||'image/png')],{type}));return c;}};
globalThis.FileReader=class{readAsArrayBuffer(blob){blob.arrayBuffer().then(b=>{this.result=b;this.onloadend?.();});}};
T.TextureLoader.prototype.load=function(){return new T.Texture();};
const dir=process.argv[2],out=process.argv[3];
const read=async p=>{const b=await fs.readFile(p);return b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength);};
const model=new FBXLoader().parse(await read(dir+'/zombieApocalypseMan.fbx'),'');
const anim=new FBXLoader().parse(await read(dir+'/Animations/Idle.fbx'),'');
console.log('model',model.children.map(c=>c.name),'clips',anim.animations.map(c=>[c.name,c.tracks.length]),'bones');
const names=[];model.traverse(o=>{if(o.isBone)names.push(o.name);});console.log(names.slice(0,15));console.log(anim.animations[0]?.tracks.slice(0,5).map(t=>t.name));
const tex=new T.Texture(await loadImage(dir+'/zombieApocalypseManBase.png'));tex.colorSpace=T.SRGBColorSpace;tex.needsUpdate=true;
model.traverse(o=>{if(o.isMesh)o.material=new T.MeshStandardMaterial({map:tex,roughness:.9,metalness:0});});
const clips=anim.animations.map(c=>{c.name='Idle';return c;});
const glb=await new GLTFExporter().parseAsync(model,{binary:true,animations:clips,maxTextureSize:1024});await fs.writeFile(out,new Uint8Array(glb));console.log('wrote',glb.byteLength);
